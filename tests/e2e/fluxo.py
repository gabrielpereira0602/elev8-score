# Teste de ponta a ponta do modo real (com o simulador em localhost:4010 e o site em localhost:3102).
import re, sys
from playwright.sync_api import sync_playwright
B="http://localhost:3102"; erros=[]; ok=[]
def checa(nome, cond, det=""):
    (ok if cond else erros).append(f"{'ok  ' if cond else 'FALHA'} {nome} {det}")
with sync_playwright() as p:
    b=p.chromium.launch(); c=b.new_context(viewport={"width":390,"height":844}); pg=c.new_page()
    pg.on("pageerror", lambda e: erros.append(f"erro de página: {e}"))
    pg.goto(B+"/"); pg.wait_for_timeout(500)
    checa("landing sem promessa do teste das IAs", "teste das IAs" not in pg.inner_text("body"))
    pg.fill("#busca-empresa","Studio Bem"); pg.wait_for_timeout(1200)
    pg.get_by_role("button", name=re.compile("Studio Bem Estar Teste")).click(); pg.wait_for_timeout(1200)
    checa("confirmação abre com a empresa real", "Studio Bem Estar Teste" in pg.inner_text("body"))
    pg.get_by_role("button", name="Está certo, continuar").click(); pg.wait_for_timeout(300)
    checa("pede as 3 respostas", "Responda as 3" in pg.inner_text("body"))
    pg.get_by_role("button", name="Não", exact=True).click()
    pg.get_by_role("button", name="1 vez").click()
    pg.get_by_role("button", name="Algumas").click()
    pg.get_by_role("button", name="Está certo, continuar").click(); pg.wait_for_timeout(400)
    pg.fill("#contato-nome","Ana Teste"); pg.fill("#contato-whats","19999990000"); pg.fill("#contato-email","ana@teste.com")
    pg.locator("input[type=checkbox]").check()
    pg.get_by_role("button", name=re.compile("Ver meu Score")).click()
    pg.wait_for_url(re.compile(r"/painel\?d="), timeout=20000); pg.wait_for_timeout(1200)
    url=pg.url; codigo=url.split("d=")[1].split("&")[0]
    t=pg.inner_text("body")
    checa("painel real abre com o código", len(codigo)==36, codigo)
    checa("painel mostra a empresa real", "Studio Bem Estar Teste" in t)
    checa("painel sem barra de protótipo", "PROTÓTIPO" not in t.upper().split("ELEV8 SCORE")[0] and "Protótipo" not in t[:400])
    checa("posição real no Maps", "3º no Google Maps" in t)
    checa("concorrente real no ranking", "Clínica Alfa" in t)
    checa("sem texto quebrado no painel", not re.search(r"\bundefined\b|\bNaN\b", t))
    pg.goto(B+f"/painel/assistente?d={codigo}"); pg.wait_for_timeout(500)
    checa("consultor bloqueado antes de pagar", "Liberar kit e consultor" in pg.inner_text("body"))
    pg.goto(B+f"/painel?d={codigo}"); pg.wait_for_timeout(800)
    pg.locator("#oferta a", has_text="Liberar kit e consultor").click()
    pg.wait_for_url(re.compile("pagamento=ok"), timeout=20000); pg.wait_for_timeout(1200)
    checa("pagamento confirmado na volta", "Pagamento confirmado" in pg.inner_text("body"))
    pg.goto(B+f"/painel/kit?d={codigo}"); pg.wait_for_timeout(800)
    checa("kit liberado pede os dados do negócio", "Deixe o kit com a cara" in pg.inner_text("body"))
    pg.get_by_label("Serviço principal *").fill("limpeza de pele")
    pg.get_by_label("O que faz você diferente dos concorrentes? *").fill("Avaliação da pele incluída")
    pg.get_by_role("button", name="Montar meu kit").click(); pg.wait_for_timeout(1500)
    checa("kit salvo", "Kit montado com os dados" in pg.inner_text("body"))
    pg.goto(B+f"/painel/plano?d={codigo}"); pg.wait_for_timeout(800)
    caixas=pg.locator("main button[aria-pressed], main input[type=checkbox]")
    checa("plano tem ações", caixas.count()>0, str(caixas.count()))
    if caixas.count()>0: caixas.first.click(); pg.wait_for_timeout(800)
    pg.reload(); pg.wait_for_timeout(800)
    t=pg.inner_text("body")
    checa("ação do plano continua marcada depois de recarregar", "1 de 12" in t or "1/12" in t, re.findall(r"\d+ de 12", t)[:2])
    pg.goto(B+f"/painel/assistente?d={codigo}"); pg.wait_for_timeout(600)
    checa("consultor liberado e com a empresa", "Studio Bem Estar Teste" in pg.inner_text("body") and "Biblioteca" in pg.inner_text("body"))
    pg.goto(B+"/admin"); pg.wait_for_timeout(500)
    checa("admin pede login", "/admin/login" in pg.url)
    pg.fill("#senha","senha-de-teste"); pg.get_by_role("button", name="Entrar").click(); pg.wait_for_timeout(1200)
    t=pg.inner_text("body")
    checa("admin mostra o lead real", "Studio Bem Estar Teste" in t and "Dados reais" in t)
    pg.goto(B+"/admin/prospeccao"); pg.wait_for_timeout(700)
    checa("prospecção mostra concorrentes reais", "Clínica Alfa" in pg.inner_text("body"))
    w=pg.evaluate("document.documentElement.scrollWidth"); checa("sem rolagem lateral no celular", w<=390, str(w))
    b.close()
print("\n".join(ok+erros)); print(f"\n{len(ok)} ok, {len(erros)} falha(s)")
sys.exit(1 if erros else 0)
